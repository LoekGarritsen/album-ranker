// Matches strings that are only emoji (plus joiners/modifiers/whitespace),
// used to render short emoji-only messages jumbo-sized.
const EMOJI_ONLY_RE = /^(?:\p{Extended_Pictographic}|\p{Emoji_Presentation}|[\u{1F3FB}-\u{1F3FF}‍️⃣\s])+$/u

export function isEmojiOnly(text) {
  const t = (text || '').trim()
  if (!t || t.length > 20) return false
  return EMOJI_ONLY_RE.test(t)
}
